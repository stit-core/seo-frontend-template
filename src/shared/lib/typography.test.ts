import { bindNumbers } from './typography'

describe('bindNumbers', () => {
  it('подпись и следующее за ней число — неразрывным пробелом, прочие пробелы — как есть', () => {
    expect(bindNumbers('ООО «Пример», ОГРН 1000000000001, ИНН 7700000000')).toBe(
      'ООО «Пример», ОГРН\u00a01000000000001, ИНН\u00a07700000000',
    )
    expect(bindNumbers('Primer LLC, OGRN 1000000000001')).toBe(
      'Primer LLC, OGRN\u00a01000000000001',
    )
    // Число после знака препинания — не подпись: пробел остаётся переносом.
    expect(bindNumbers('Пн–Пт, 10:00–19:00')).toBe('Пн–Пт, 10:00–19:00')
  })
})
