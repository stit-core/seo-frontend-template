// Подпись и число после неё — неразрывным пробелом, как ставит автотипограф (typograf, ru/nbsp): в реквизитах «ИНН» не
// остаётся в конце строки без номера, «офис» — без своего «2». Для чтеца и сверки текста неразрывный пробел — пробел.
export const bindNumbers = (text: string): string =>
  text.replace(/(?<=\p{L}) (?=\p{N})/gu, '\u00a0')
